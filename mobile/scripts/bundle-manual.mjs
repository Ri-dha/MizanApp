// Metro cannot import Markdown, so the manual is baked into a module the app imports; rerun after editing docs/manual.
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const root = join(import.meta.dirname, "..", "..", "docs", "manual")
const out = join(import.meta.dirname, "..", "src", "help", "manual.generated.ts")
const raw = {}
for (const lang of readdirSync(root).sort()) {
  for (const file of readdirSync(join(root, lang)).filter((f) => f.endsWith(".md")).sort()) {
    raw[`docs/manual/${lang}/${file}`] = readFileSync(join(root, lang, file), "utf8")
  }
}
writeFileSync(out, `// Generated by scripts/bundle-manual.mjs from docs/manual; do not edit.\nexport const MANUAL: Record<string, string> = ${JSON.stringify(raw, null, 2)}\n`)
console.log(`manual: ${Object.keys(raw).length} pages`)
