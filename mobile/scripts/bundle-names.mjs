// Hermes has no Intl.DisplayNames, so country and currency names are baked in from Node's ICU; rerun after a Node upgrade.
import { writeFileSync } from "node:fs"
import { join } from "node:path"

const out = join(import.meta.dirname, "..", "src", "i18n", "names.generated.ts")
const LETTERS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
const regions = []
for (const a of LETTERS) for (const b of LETTERS) regions.push(a + b)
const currencies = Intl.supportedValuesOf("currency")

const names = {}
for (const language of ["en", "ar"]) {
  const region = new Intl.DisplayNames([language], { type: "region", fallback: "none" })
  const currency = new Intl.DisplayNames([language], { type: "currency", fallback: "none" })
  const countries = {}
  for (const code of regions) {
    const name = region.of(code)
    if (name && name !== code) countries[code] = name
  }
  const money = {}
  for (const code of currencies) {
    const name = currency.of(code)
    if (name && name !== code) money[code] = name
  }
  names[language] = { countries, currencies: money }
}
writeFileSync(out, `// Generated by scripts/bundle-names.mjs; do not edit.\nexport const NAMES: Record<string, { countries: Record<string, string>; currencies: Record<string, string> }> = ${JSON.stringify(names)}\n`)
console.log(`names: ${Object.keys(names.en.countries).length} countries, ${Object.keys(names.en.currencies).length} currencies`)
